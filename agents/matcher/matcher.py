"""
Matcher agent — scores opportunities against a company profile and
produces ranked Recommendation objects.

Imports all shared types from contracts.models (source of truth).

Scoring formula (weights in config.py):
  score = w_topic * topic_overlap
        + w_timeline * timeline_score
        + w_location * location_format_score

user_confirmed claims receive a boost (config.USER_CONFIRMED_BOOST) in the
topic overlap calculation so they visibly affect the ranking.

The `why` field is generated by an LLM if LLM_API_KEY is set, otherwise
a deterministic fallback is used so the demo works offline.
"""
from __future__ import annotations

import logging
import os
from datetime import date, timedelta
from typing import List, Optional, Sequence

from contracts.models import (
    Claim,
    ClaimKind,
    Opportunity,
    OpportunityFormat,
    Profile,
    Recommendation,
)

from . import config

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Helpers — topic field names (must match ProfileField enum values)
# ---------------------------------------------------------------------------

TOPIC_FIELDS = {
    "technologies",
    "expertise",
    "topics",
    "products_services",
    "application_areas",
    "markets",
    "industries",
    "development_priorities",
    "projects",
    "collaborations",
    "what_it_does",
    "customer_groups",
}


# ---------------------------------------------------------------------------
# Sub-scorers
# ---------------------------------------------------------------------------

def _topic_overlap_score(
    profile: Profile,
    opportunity: Opportunity,
) -> tuple[float, List[Claim]]:
    """
    Jaccard-style overlap between opportunity topics and profile claim values.
    user_confirmed claims receive a boost (USER_CONFIRMED_BOOST).

    Returns (score 0–1, list of matched claims).
    """
    if not opportunity.topics:
        return 0.0, []

    opp_topics = {t.lower().strip() for t in opportunity.topics}
    matched: List[Claim] = []
    weighted_hits = 0.0
    weighted_total = 0.0

    for claim in profile.claims:
        if claim.field.value not in TOPIC_FIELDS:
            continue

        weight = (
            config.USER_CONFIRMED_BOOST
            if claim.kind == ClaimKind.user_confirmed
            else 1.0
        )
        weighted_total += weight

        claim_tokens = set(claim.value.lower().split())
        # Match if any opportunity topic is contained in the claim value OR
        # any claim token is contained in an opportunity topic
        if any(
            tok in opp_topic or opp_topic in claim.value.lower()
            for opp_topic in opp_topics
            for tok in claim_tokens
            if len(tok) > 2  # skip short stop-words
        ):
            weighted_hits += weight
            matched.append(claim)

    if weighted_total == 0:
        return 0.0, []

    # Jaccard-ish: hits / (total_claims + opp_topics - hits)
    union = weighted_total + len(opp_topics) - weighted_hits
    score = weighted_hits / union if union > 0 else 0.0
    return min(score, 1.0), matched


def _timeline_score(opportunity: Opportunity, today: Optional[date] = None) -> float:
    """
    Returns a score 0–1 based on how soon the relevant date is.
    Closer deadlines score higher (more urgency = more relevant now).
    """
    if today is None:
        today = date.today()

    relevant = opportunity.deadline or opportunity.event_date or opportunity.published
    if relevant is None:
        return config.TIMELINE_NO_DATE_SCORE

    days_until = (relevant - today).days

    if days_until < 0:
        # Already passed — still potentially useful for discovery, low score
        return 0.1

    full = config.TIMELINE_FULL_SCORE_DAYS
    zero = config.TIMELINE_ZERO_SCORE_DAYS

    if days_until <= full:
        return 1.0
    if days_until >= zero:
        return 0.0

    # Linear decay between full and zero
    return 1.0 - (days_until - full) / (zero - full)


def _location_format_score(
    profile: Profile,
    opportunity: Opportunity,
) -> float:
    """
    Returns 1.0 for online opportunities (universally accessible),
    or checks geographic overlap if the opportunity is in_person.
    """
    if opportunity.format == OpportunityFormat.online:
        return 1.0

    geo_claims = [c for c in profile.claims if c.field.value == "geographic_focus"]
    if not geo_claims:
        # No geographic restriction stated — assume open
        return 0.7

    if opportunity.format is None:
        # Format not specified — moderate score
        return 0.6

    # in_person: check if audience or eligibility mentions the company's region
    audience_text = (
        (opportunity.audience or "") + " " + (opportunity.eligibility_text or "")
    ).lower()

    for claim in geo_claims:
        # Check each part of the geo value (e.g. "Sweden, Finland and Norway")
        for region in claim.value.lower().replace(",", " ").replace(" and ", " ").split():
            if len(region) > 2 and region in audience_text:
                return 1.0

    return 0.3  # In-person but region mismatch


# ---------------------------------------------------------------------------
# `why` generation
# ---------------------------------------------------------------------------

def _build_why_deterministic(
    profile: Profile,
    opportunity: Opportunity,
    matched_claims: List[Claim],
) -> str:
    """Fallback `why` when no LLM is available. Always returns a non-empty string."""
    claim_summaries = "; ".join(
        f"'{c.value}' ({c.field.value})" for c in matched_claims[:3]
    )
    suffix = f" and {len(matched_claims) - 3} more" if len(matched_claims) > 3 else ""
    return (
        f"'{opportunity.title}' matches {profile.name} because of overlapping "
        f"topics with: {claim_summaries}{suffix}."
    )


def _build_why_llm(
    profile: Profile,
    opportunity: Opportunity,
    matched_claims: List[Claim],
    score: float,
) -> str:
    """
    Call an LLM to generate a human-readable `why` sentence.
    Reads model/key/base_url from environment via config.
    Returns deterministic fallback on any error.
    """
    try:
        import openai  # type: ignore

        client_kwargs: dict = {"api_key": config.LLM_API_KEY}
        if config.LLM_BASE_URL:
            client_kwargs["base_url"] = config.LLM_BASE_URL

        client = openai.OpenAI(**client_kwargs)

        claim_lines = "\n".join(
            f"- [{c.kind.value}] {c.field.value}: {c.value}" for c in matched_claims[:5]
        )
        prompt_path = os.path.join(os.path.dirname(__file__), "prompts", "why_v1.md")
        with open(prompt_path) as fh:
            system_prompt = fh.read()

        user_message = (
            f"Company: {profile.name}\n"
            f"Opportunity: {opportunity.title} ({opportunity.type.value})\n"
            f"Opportunity topics: {', '.join(opportunity.topics)}\n"
            f"Matched profile claims:\n{claim_lines}\n"
            f"Score: {score:.0%}\n"
            "Write a one-sentence explanation of why this opportunity matches."
        )

        response = client.chat.completions.create(
            model=config.LLM_MODEL,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message},
            ],
            max_tokens=120,
            temperature=0.3,
        )
        return response.choices[0].message.content.strip()

    except Exception as exc:  # noqa: BLE001
        logger.warning("LLM why-generation failed (%s); using deterministic fallback.", exc)
        return _build_why_deterministic(profile, opportunity, matched_claims)


def _build_why(
    profile: Profile,
    opportunity: Opportunity,
    matched_claims: List[Claim],
    score: float,
) -> str:
    if config.LLM_API_KEY:
        return _build_why_llm(profile, opportunity, matched_claims, score)
    return _build_why_deterministic(profile, opportunity, matched_claims)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def match(
    profile: Profile,
    opportunities: Sequence[Opportunity],
    today: Optional[date] = None,
) -> List[Recommendation]:
    """
    Score every opportunity against the company profile and return a list of
    Recommendation objects sorted by descending score.

    Only results with:
      - score >= config.MIN_SCORE_THRESHOLD
      - at least 1 matched claim (required by contracts.models.Recommendation)
    are returned.
    """
    results: List[Recommendation] = []

    for opp in opportunities:
        topic_score, matched_claims = _topic_overlap_score(profile, opp)
        timeline_sc = _timeline_score(opp, today=today)
        location_sc = _location_format_score(profile, opp)

        score = (
            config.WEIGHT_TOPIC_OVERLAP * topic_score
            + config.WEIGHT_TIMELINE * timeline_sc
            + config.WEIGHT_LOCATION_FORMAT * location_sc
        )
        score = round(min(max(score, 0.0), 1.0), 4)

        # Contract requires matched_claims min_length=1
        if not matched_claims:
            logger.debug("Skipping '%s' — no matched claims.", opp.title)
            continue

        if score < config.MIN_SCORE_THRESHOLD:
            logger.debug("Skipping '%s' — score %.4f below threshold.", opp.title, score)
            continue

        why = _build_why(profile, opp, matched_claims, score)

        rec = Recommendation(
            company_id=profile.company_id,
            opportunity_id=opp.id,
            score=score,
            why=why,
            matched_claims=[c.id for c in matched_claims],
            caveats="Potential match — eligibility not confirmed.",
        )
        results.append(rec)

    results.sort(key=lambda r: r.score, reverse=True)
    logger.info(
        "Matched %d/%d opportunities for company '%s'.",
        len(results),
        len(opportunities),
        profile.company_id,
    )
    return results
